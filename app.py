# LỚP PHÁT HIỆN GIAO DỊCH BẤT THƯỜNG (DÙNG QUEUE, HASH TABLE, HEAP)
# =====================================================================
class FraudDetector:
    def __init__(self, max_tx_in_window=3, window_seconds=600, amount_threshold_multiplier=3.0, fixed_amount_threshold=1000):
        """
        - max_tx_in_window: Ngưỡng giao dịch trong cửa sổ thời gian
        - window_seconds: Cửa sổ trượt tính bằng giây
        - amount_threshold_multiplier: Ngưỡng gấp N lần chi tiêu trung bình cũ
        - fixed_amount_threshold: Ngưỡng số tiền cố định bất thường
        """
        self.max_tx_in_window = max_tx_in_window
        self.window_seconds = window_seconds
        self.amount_threshold_multiplier = amount_threshold_multiplier
        self.fixed_amount_threshold = fixed_amount_threshold

        # 1. Cấu trúc QUEUE (deque) cho Cửa sổ trượt
        self.card_queues = defaultdict(deque)

        # 2. Cấu trúc HASH TABLE (dict) lưu lịch sử chi tiêu từng thẻ
        self.card_history = defaultdict(lambda: {'total_amount': 0.0, 'count': 0})

        # 3. Cấu trúc HEAP (Min-Heap) lưu Top N giao dịch lớn nhất
        self.top_n_heap = []

    def process_transaction(self, tx_id, card_id, timestamp, amount, top_n=5):
        alerts = []

        # -------------------------------------------------------------
        # 1. XỬ LÝ CỬA SỔ TRƯỢT BẰNG QUEUE
        # -------------------------------------------------------------
        q = self.card_queues[card_id]

        # Loại bỏ các giao dịch cũ ngoài cửa sổ thời gian khỏi đầu Queue
        while q and (timestamp - q[0][0]).total_seconds() > self.window_seconds:
            q.popleft()

        # Thêm giao dịch hiện tại vào cuối Queue
        q.append((timestamp, tx_id))

        # Kiểm tra tần suất giao dịch
        if len(q) > self.max_tx_in_window:
            alerts.append(
                f"[CẢNH BÁO TẦN SUẤT] Thẻ {card_id} thực hiện {len(q)} giao dịch "
                f"trong vòng {self.window_seconds // 60} phút (Vượt ngưỡng > {self.max_tx_in_window})."
            )

        # -------------------------------------------------------------
        # 2. XỬ LÝ SỐ TIỀN BẤT THƯỜNG BẰNG HASH TABLE
        # -------------------------------------------------------------
        history = self.card_history[card_id]

        # Kiểm tra vượt ngưỡng cố định
        if amount >= self.fixed_amount_threshold:
            alerts.append(
                f"[CẢNH BÁO SỐ TIỀN] Giao dịch ${amount:,.2f} vượt ngưỡng cố định (${self.fixed_amount_threshold:,.2f})."
            )

        # Kiểm tra gấp nhiều lần trung bình lịch sử của thẻ
        if history['count'] > 0:
            avg_amount = history['total_amount'] / history['count']
            if amount > avg_amount * self.amount_threshold_multiplier:
                alerts.append(
                    f"[CẢNH BÁO CHI TIÊU ĐỘT BIẾN] Số tiền ${amount:,.2f} gấp "
                    f"{amount / avg_amount:.1f}x so với trung bình lịch sử (${avg_amount:,.2f})."
                )

        # Cập nhật lịch sử chi tiêu vào Hash Table
        history['total_amount'] += amount
        history['count'] += 1

        # -------------------------------------------------------------
        # 3. QUẢN LÝ TOP N GIAO DỊCH LỚN NHẤT BẰNG HEAP
        # -------------------------------------------------------------
        heap_item = (amount, tx_id, card_id, timestamp.strftime("%Y-%m-%d %H:%M:%S"))
        if len(self.top_n_heap) < top_n:
            heapq.heappush(self.top_n_heap, heap_item)
        else:
            if amount > self.top_n_heap[0][0]:
                heapq.heappushpop(self.top_n_heap, heap_item)

        return alerts

    def get_top_n_transactions(self):
        """Trả về danh sách Top N giao dịch xếp từ lớn đến nhỏ."""
        return sorted(self.top_n_heap, key=lambda x: x[0], reverse=True)


